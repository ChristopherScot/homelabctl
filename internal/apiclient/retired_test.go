package apiclient_test

import (
	"os"
	"path/filepath"
	"slices"
	"testing"

	"github.com/ChristopherScot/homelabctl/internal/apiclient"
)

// A retired file as it sits in a consumer's repo today: the header
// this package writes, over a body it no longer renders.
//
// Built from Header rather than pasted, so this fixture cannot be the
// one place that still carries an outdated copy of the wording - the
// failure it exists to catch. The body is arbitrary; only the header
// decides whether the file may be deleted.
var retiredFile = apiclient.Header("//") + "\npackage api\n\nfunc TestX(t *testing.T) {}\n"

// A file this package used to write and no longer does has to be
// removed, not merely stopped. Otherwise it stays in every repo that
// ever ran the generator, owned by nobody, drifting from a template
// that keeps moving, while still telling its reader not to edit it.
func TestRetiredFilesAreRemoved(t *testing.T) {
	// Named, not ranged over Retired: a test that reads its subject
	// from the list under test cannot notice the list losing an entry,
	// it just checks less.
	retired := []string{"client_test.go", "paging_test.go"}

	dir := t.TempDir()
	for _, name := range retired {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(retiredFile), 0o644); err != nil {
			t.Fatalf("writing the stale %s: %v", name, err)
		}
	}

	removed, err := apiclient.RemoveRetired(dir)
	if err != nil {
		t.Fatalf("RemoveRetired(%q): %v", dir, err)
	}

	for _, name := range retired {
		if _, err := os.Stat(filepath.Join(dir, name)); !os.IsNotExist(err) {
			t.Errorf("after RemoveRetired(%q), %s still exists; want it gone - "+
				"it is no longer generated, so nothing will update it again", dir, name)
		}
		if !slices.Contains(removed, name) {
			t.Errorf("RemoveRetired(%q) did not report removing %s; "+
				"the caller cannot tell the consumer what it did", dir, name)
		}
	}
}

// Only files this package wrote. A consumer who writes their own
// client_test.go beside a generated client is doing a reasonable
// thing, and a generator that deletes it is not.
func TestAHandWrittenFileSurvives(t *testing.T) {
	for _, tc := range []struct{ name, body string }{
		{"no marker at all", "package api\n\n// mine, not the generator's\n"},
		// The file a consumer is MOST likely to write: a replacement
		// that names what it replaced. Scanning the whole body for the
		// marker reads this as a claim of ownership and deletes it.
		{"mentions the generator in prose",
			"package api\n\n// Replaces the one Generated by homelabctl, which was wrong.\n" +
				"func TestMine(t *testing.T) {}\n"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			mine := filepath.Join(dir, "client_test.go")
			if err := os.WriteFile(mine, []byte(tc.body), 0o644); err != nil {
				t.Fatalf("writing the hand-written file: %v", err)
			}

			removed, err := apiclient.RemoveRetired(dir)
			if err != nil {
				t.Fatalf("RemoveRetired(%q): %v", dir, err)
			}
			if len(removed) != 0 {
				t.Errorf("RemoveRetired(%q) removed %v; want nothing", dir, removed)
			}

			got, err := os.ReadFile(mine)
			if err != nil {
				t.Fatalf("a hand-written client_test.go was deleted: %v", err)
			}
			if string(got) != tc.body {
				t.Error("a hand-written client_test.go was modified")
			}
		})
	}
}

// The usual case: nothing to do, and nothing to report. A service
// scaffolded after these were dropped never had them.
func TestRemovingWhatIsNotThereIsNotAnError(t *testing.T) {
	dir := t.TempDir()
	removed, err := apiclient.RemoveRetired(dir)
	if err != nil {
		t.Errorf("RemoveRetired(%q) on an empty directory: %v", dir, err)
	}
	if len(removed) != 0 {
		t.Errorf("RemoveRetired(%q) = %v; want nothing", dir, removed)
	}
}

// Retired must name nothing any list still ships, or the generator
// would write a file and then immediately delete it.
func TestRetiredNamesNothingStillShipped(t *testing.T) {
	p := apiclient.Params{
		Name: "x", Version: "1.0.0", Package: "api", ImportPath: "example.com/x",
	}
	shipped := map[string]bool{}
	for _, set := range []func(apiclient.Params) ([]apiclient.File, error){
		apiclient.Go, apiclient.TypeScript,
	} {
		files, err := set(p)
		if err != nil {
			t.Fatal(err)
		}
		for _, f := range files {
			shipped[f.Path] = true
		}
	}
	for _, name := range apiclient.Retired {
		if shipped[name] {
			t.Errorf("%s is in Retired and still shipped: it would be written, then deleted", name)
		}
	}
}

// Every file the generator writes has to be claimable by the check
// that decides whether to delete it. They are written from different
// templates with different headers, and only one of those headers is
// GeneratedHeader.
func TestWroteItClaimsEveryGeneratedFile(t *testing.T) {
	p := apiclient.Params{
		Name: "x", Version: "1.0.0", Package: "api", ImportPath: "example.com/x",
	}
	for _, set := range []struct {
		name  string
		files func(apiclient.Params) ([]apiclient.File, error)
	}{
		{"Go", apiclient.Go},
		{"TypeScript", apiclient.TypeScript},
		{"GoTests", apiclient.GoTests},
		{"TypeScriptTests", apiclient.TypeScriptTests},
	} {
		files, err := set.files(p)
		if err != nil {
			t.Fatal(err)
		}
		for _, f := range files {
			if !apiclient.WroteIt([]byte(f.Body)) {
				t.Errorf("WroteIt says %s/%s is not ours; if it is ever retired it will "+
					"be left behind", set.name, f.Path)
			}
		}
	}
	if !apiclient.WroteIt([]byte(apiclient.GeneratedHeader())) {
		t.Error("WroteIt does not claim GeneratedHeader, which MarkGenerated writes")
	}
}

// The files RemoveRetired has to claim are the ones already on disk in
// consumer repos, written by OLDER versions of this tool. Nothing else
// here tests against those: every other fixture is built from Header,
// so the code and the bytes it must recognise could drift apart
// together and every test would still pass. That is the shape of the
// bug this whole mechanism was written for.
//
// So pin a literal. This is the first line of
// services/pokedex/api/client_test.go as homelabctl shipped it, copied
// rather than generated. If a change makes WroteIt stop claiming it,
// every client generated before that change becomes unretirable and
// the file is orphaned for good.
func TestWroteItStillClaimsWhatOlderVersionsWrote(t *testing.T) {
	for _, shipped := range []struct{ name, head string }{
		{"go", "// Generated by homelabctl. Do not edit: `homelabctl regen` and\n"},
		{"ts", "/* eslint-disable */\n// Generated by homelabctl. Do not edit: `homelabctl regen` and\n"},
		// The shorter notice MarkGenerated wrote onto hey-api's
		// output before the two were merged.
		{"hey-api", "/* eslint-disable */\n// Generated by homelabctl. Do not edit.\n"},
	} {
		if !apiclient.WroteIt([]byte(shipped.head + "\npackage api\n")) {
			t.Errorf("WroteIt no longer claims the %s header that shipped to consumers; "+
				"every client generated with it can never be cleaned up:\n%s",
				shipped.name, shipped.head)
		}
	}
}
